#!/usr/bin/env python3
"""Build paperboard/common/font8x16_basic.h from a fixed-width BDF bitmap font.

The console renders with bit 0 of every font row on the left, while BDF stores
bit 7 on the left, so rows are mirrored while converting.

Usage:
    python3 bdf-to-font.py FONT.bdf header font8x16_basic.h [preview.png]

The preview renders a mock 30x15 console screen scaled 3x so it can be checked
by eye.
"""
import struct
import sys
import zlib

CELL_W, CELL_H = 8, 16


def parse_bdf(path):
    props, glyphs, cur = {}, {}, None
    for line in open(path, encoding='latin-1'):
        line = line.rstrip('\n')
        if line.startswith('STARTCHAR'):
            cur = {'bitmap': [], 'bbx': None, 'encoding': None, 'bitmap_started': False}
        elif line.startswith('FONT_ASCENT'):
            props['ascent'] = int(line.split()[1])
        elif line.startswith('FONT_DESCENT'):
            props['descent'] = int(line.split()[1])
        elif cur is not None:
            if line.startswith('ENCODING'):
                cur['encoding'] = int(line.split()[1])
            elif line.startswith('BBX'):
                cur['bbx'] = tuple(int(v) for v in line.split()[1:5])
            elif line.startswith('BITMAP'):
                cur['bitmap_started'] = True
            elif line.startswith('ENDCHAR'):
                if cur['encoding'] is not None:
                    glyphs[cur['encoding']] = cur
                cur = None
            elif cur['bitmap_started']:
                cur['bitmap'].append(int(line, 16))
    return props, glyphs


def build_cells(props, glyphs):
    ascent = props['ascent']
    cells = [[0] * CELL_H for _ in range(128)]
    for enc in range(32, 127):
        g = glyphs.get(enc)
        if g is None:
            raise SystemExit('BDF is missing glyph %d' % enc)
        w, h, xoff, yoff = g['bbx']
        if w > CELL_W or h > CELL_H:
            raise SystemExit('glyph %d does not fit the cell' % enc)
        top = ascent - (yoff + h)
        for by, byte in enumerate(g['bitmap'][:h]):
            y = top + by
            if not 0 <= y < CELL_H:
                continue
            for x in range(w):
                if byte >> (7 - x) & 1:
                    cx = xoff + x
                    if 0 <= cx < CELL_W:
                        cells[enc][y] |= 1 << cx  # bit 0 = leftmost pixel
    return cells


def emit_header(cells, out):
    out.write('\n')
    out.write('/* GENERATED by tools/bdf-to-font.py -- do not edit by hand.\n')
    out.write(' *\n')
    out.write(' * 8x16 ASCII cell font for the Paperboard TFT console, converted from\n')
    out.write(' * Spleen 8x16 (https://github.com/fcambus/spleen).\n')
    out.write(' *\n')
    out.write(' * Copyright (c) 2018-2026, Frederic Cambus, BSD 2-Clause license.\n')
    out.write(' * The full license text ships next to this file as font8x16-basic.LICENSE.\n')
    out.write(' *\n')
    out.write(' * Table convention: font8x16_basic[c][y] is one scanline, bit 0 is the\n')
    out.write(' * leftmost pixel. Glyphs 0..31 are blank. */\n')
    out.write('static const uint8_t font8x16_basic[128][16] = {\n')
    for enc, rows in enumerate(cells):
        shown = '.' if enc < 32 else (chr(enc) if enc < 127 else '?')
        comment = ' /* %s */' % (shown if shown != '*' else "'*'")
        out.write('    {%s},%s\n' % (','.join('0x%02x' % b for b in rows), comment))
    out.write('};\n')


def write_png(path, width, height, rows):
    def chunk(tag, data):
        return (struct.pack('>I', len(data)) + tag + data +
                struct.pack('>I', zlib.crc32(tag + data) & 0xffffffff))
    raw = b''.join(b'\x00' + row for row in rows)
    png = (b'\x89PNG\r\n\x1a\n' +
           chunk(b'IHDR', struct.pack('>IIBBBBB', width, height, 8, 2, 0, 0, 0)) +
           chunk(b'IDAT', zlib.compress(raw, 9)) + chunk(b'IEND', b''))
    open(path, 'wb').write(png)


def preview(cells, path, scale=3):
    width, height = 240, 240
    pixels = [[(255, 255, 255)] * width for _ in range(height)]
    lines = [
        'Paperboard / JLX130-026',
        '30 columns x 15 rows, 8x16',
        'ABCDEFGHIJKLMNOPQRSTUVWXYZ+<>',
        'abcdefghijklmnopqrstuvwxyz+@',
        '0123456789 !"#$%&\'()*+,-./:;',
        '<=>?@[\\]^_`{|}~',
    ]
    for row, text in enumerate(lines):
        for col, ch in enumerate(text[:30]):
            for y in range(CELL_H):
                bits = cells[ord(ch)][y]
                for x in range(CELL_W):
                    if bits >> x & 1:
                        pixels[row * CELL_H + y][col * CELL_W + x] = (0, 0, 0)
    # Inverse cell and cursor sample on the last row.
    for y in range(CELL_H):
        for x in range(CELL_W):
            pixels[14 * CELL_H + y][x] = (0, 0, 0)          # inverse blank block
            if y >= CELL_H - 2:
                pixels[14 * CELL_H + y][3 * CELL_W + x] = (0, 0, 0)  # cursor underline
    rows = []
    for y in range(height):
        row = bytearray()
        for x in range(width):
            r, g, b = pixels[y][x]
            row += bytes((r, g, b)) * scale
        rows.extend([bytes(row)] * scale)
    write_png(path, width * scale, height * scale, rows)


def main():
    bdf, header, *rest = sys.argv[1:]
    props, glyphs = parse_bdf(bdf)
    cells = build_cells(props, glyphs)
    with open(header, 'w', newline='\n') as out:
        emit_header(cells, out)
    if rest:
        preview(cells, rest[0])
    print('wrote %s (%d glyphs, ascent %d)' % (header, len(cells), props['ascent']))


if __name__ == '__main__':
    main()
